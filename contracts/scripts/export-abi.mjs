// Copies the compiled BarDice ABI into the web app as a typed `as const` module.
// Run automatically by `pnpm compile`; CI fails if the committed file is stale.
import { readFileSync, writeFileSync } from "node:fs";

const artifact = JSON.parse(readFileSync(new URL("../artifacts/contracts/BarDice.sol/BarDice.json", import.meta.url)));
const out = new URL("../../web/src/generated/barDiceAbi.ts", import.meta.url);
writeFileSync(
  out,
  `// AUTO-GENERATED by contracts/scripts/export-abi.mjs — do not edit.\nexport const barDiceAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
);
console.log("wrote", out.pathname);
